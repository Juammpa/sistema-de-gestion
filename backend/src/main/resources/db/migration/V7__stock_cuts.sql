-- Corte de carne sacado de una pieza de una compra (stock real)
-- Cada fila es una unidad de corte con su propio peso: una pieza puede tener varias del mismo corte
CREATE TABLE stock_cuts (
        id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        owner_id     uuid          NOT NULL,
        purchase_id  bigint        NOT NULL REFERENCES purchases (id),
        piece_number integer       NOT NULL CHECK (piece_number > 0),
        cut_meat_id  bigint        NOT NULL REFERENCES cut_meats (id),
        kilograms    numeric(10,2) NOT NULL CHECK (kilograms > 0)
);

CREATE INDEX idx_stock_cuts_owner_id    ON stock_cuts (owner_id);
CREATE INDEX idx_stock_cuts_purchase_id ON stock_cuts (purchase_id);
CREATE INDEX idx_stock_cuts_cut_meat_id ON stock_cuts (cut_meat_id);