-- Los tipos de compra dejan de ser un enum fijo y pasan a ser datos de cada usuario.
-- Esta migración solo AGREGA: la columna purchases.purchase_type se mantiene hasta refactorizar el código.

CREATE TABLE purchase_types (
                                id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                owner_id  uuid         NOT NULL,
                                specie    varchar(255) NOT NULL,
                                name      varchar(100) NOT NULL,
                                is_active boolean      NOT NULL DEFAULT true,
                                CONSTRAINT purchase_types_specie_check CHECK (specie IN ('BOVINE', 'PORCINE'))
);

CREATE INDEX idx_purchase_types_owner_id ON purchase_types (owner_id);

-- Nombre único por usuario y especie, entre los activos (los archivados no bloquean el nombre)
CREATE UNIQUE INDEX uq_purchase_types_owner_specie_name_active
    ON purchase_types (owner_id, specie, lower(name))
    WHERE is_active;

-- Equivalencia entre el enum viejo y los nuevos registros
CREATE TEMP TABLE legacy_purchase_types (code varchar(255), specie varchar(255), name varchar(100)) ON COMMIT DROP;
INSERT INTO legacy_purchase_types VALUES
