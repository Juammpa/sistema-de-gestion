-- Pieza de una compra cerrada a mano como vendida: lo que no se cortó queda como merma
-- La pieza no es una entidad: se identifica por (compra, numero de pieza); sin fila = abierta
CREATE TABLE stock_piece_closures (
      id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      owner_id     uuid    NOT NULL,
      purchase_id  bigint  NOT NULL REFERENCES purchases (id),
      piece_number integer NOT NULL CHECK (piece_number > 0),
      CONSTRAINT uq_stock_piece_closures_piece UNIQUE (purchase_id, piece_number)
);

CREATE INDEX idx_stock_piece_closures_owner_id ON stock_piece_closures (owner_id);