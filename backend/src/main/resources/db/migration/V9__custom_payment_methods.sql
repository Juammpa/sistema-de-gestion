-- Métodos de pago creados por cada usuario (se comportan como una transferencia).
-- El tipo IIBB deja de existir como valor fijo.

CREATE TABLE custom_payment_methods (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id  uuid        NOT NULL,
    name      varchar(60) NOT NULL,
    is_active boolean     NOT NULL DEFAULT true
);

CREATE INDEX idx_custom_payment_methods_owner_id ON custom_payment_methods (owner_id);

-- Nombre único por usuario entre los activos (los archivados no bloquean el nombre)
CREATE UNIQUE INDEX uq_custom_payment_methods_owner_name_active
    ON custom_payment_methods (owner_id, lower(name))
    WHERE is_active;

ALTER TABLE payments ADD COLUMN custom_payment_method_id bigint REFERENCES custom_payment_methods (id);
CREATE INDEX idx_payments_custom_payment_method_id ON payments (custom_payment_method_id);

ALTER TABLE payments DROP CONSTRAINT payments_payment_type_check;

-- Los pagos IIBB ya cargados se conservan como un método personalizado "IIBB" de cada usuario
INSERT INTO custom_payment_methods (owner_id, name)
SELECT DISTINCT m.owner_id, 'IIBB'
FROM payments p
         JOIN movements m ON m.id = p.id
WHERE p.payment_type = 'IIBB';

UPDATE payments p
SET payment_type = 'CUSTOM',
    custom_payment_method_id = cpm.id
    FROM movements m, custom_payment_methods cpm
WHERE m.id = p.id
  AND p.payment_type = 'IIBB'
  AND cpm.owner_id = m.owner_id
  AND cpm.name = 'IIBB';

ALTER TABLE payments ADD CONSTRAINT payments_payment_type_check
    CHECK (payment_type IN ('TRANSFER', 'CASH', 'CHECK', 'SUPPLIER_TRANSFER', 'CHECK_REJECTION', 'CUSTOM'));

-- El método personalizado se informa si y solo si el pago es de tipo CUSTOM
ALTER TABLE payments ADD CONSTRAINT payments_custom_method_check
    CHECK ((payment_type = 'CUSTOM') = (custom_payment_method_id IS NOT NULL));