                                      ('VEAL_UP_TO_110KG', 'BOVINE',  'Ternero hasta 110 kg'),
                                      ('NT_111_120KG',     'BOVINE',  'NT 111-120 kg'),
                                      ('NT_121_130KG',     'BOVINE',  'NT 121-130 kg'),
                                      ('STEER_OVER_130KG', 'BOVINE',  'Novillo +130 kg');

-- Cada usuario recibe solo los tipos que ya había usado en sus compras
INSERT INTO purchase_types (owner_id, specie, name)
SELECT DISTINCT m.owner_id, l.specie, l.name
FROM purchases p
         JOIN movements m ON m.id = p.id
         JOIN legacy_purchase_types l ON l.code = p.purchase_type;

ALTER TABLE purchases ADD COLUMN purchase_type_id bigint REFERENCES purchase_types (id);

UPDATE purchases p
SET purchase_type_id = pt.id
    FROM movements m, legacy_purchase_types l, purchase_types pt
WHERE m.id = p.id
  AND l.code = p.purchase_type
  AND pt.owner_id = m.owner_id
  AND pt.specie = l.specie
  AND pt.name = l.name;

CREATE INDEX idx_purchases_purchase_type_id ON purchases (purchase_type_id);